import type { ComputedRef, Ref } from 'vue'
import type { WeekData } from '../types'
import type { ViewBucket } from '../utils/dateUtils'

import axios from '@nextcloud/axios'
import { getCapabilities } from '@nextcloud/capabilities'
import { generateUrl, getRootUrl } from '@nextcloud/router'
import { bucketKey } from '../utils/dateUtils'

interface PollDeps {
	bucketKeys: ComputedRef<ViewBucket[]>
	weekData: Ref<WeekData>
	editingTask: Ref<{ day: string, taskId: string } | null>
	loadWeek: () => Promise<void>
	loadCustomColumns: () => Promise<void>
	materializeRecurringTasks: () => void
	applyCustomColumnsData: (data: unknown) => void
	applyBucketData: (weekKey: string, data: WeekData) => void
	isWeekSaveIdle: () => boolean
	isWeekLoadIdle: () => boolean
	isCustomSaveIdle: () => boolean
	getWeekKnownUpdatedAt: (weekKey: string) => number
	setWeekKnownUpdatedAt: (weekKey: string, val: number) => void
	getCustomKnownUpdatedAt: () => number
	setCustomKnownUpdatedAt: (val: number) => void
}

interface NotifyPushCapability {
	endpoints?: { websocket?: string, pre_auth?: string }
}

const WS_PROBE_TIMEOUT_MS = 5_000

function sameOriginWebSocketUrls() {
	const wsProto = window.location.protocol === 'https:' ? 'wss:' : 'ws:'
	const origin = `${wsProto}//${window.location.host}`
	const root = getRootUrl()
	const urls = [`${origin}${root}/push/ws`]
	if (root) {
		// Some deployments mount the /push reverse proxy at the host root even
		// when Nextcloud itself lives under a subdirectory.
		urls.push(`${origin}/push/ws`)
	}
	return urls
}

// The notify_push SDK reads its WebSocket URL from the notify_push capability.
// In a normal install that endpoint is correct, so use it as-is. The dev
// docker-compose setup advertises an internal hostname that browsers cannot
// reach, so keep same-origin fallbacks for when the advertised endpoint fails.
// The `pre_auth` endpoint is generated by Nextcloud's URL generator against
// the request host, so it's already same-origin and we leave it alone.
async function resolveNotifyPushWebsocket(notifyPush: NotifyPushCapability): Promise<string | null> {
	const advertised = notifyPush.endpoints?.websocket
	const candidates = [...new Set([
		...(advertised ? [advertised] : []),
		...sameOriginWebSocketUrls(),
	])]
	for (const candidate of candidates) {
		if (await probeWebSocket(candidate)) {
			return candidate
		}
	}
	return null
}

function probeWebSocket(url: string, timeoutMs = WS_PROBE_TIMEOUT_MS): Promise<boolean> {
	return new Promise((resolve) => {
		let settled = false
		let socket: WebSocket | null = null
		const timerHolder: { id: ReturnType<typeof setTimeout> | null } = { id: null }
		const finish = (ok: boolean) => {
			if (settled) {
				return
			}
			settled = true
			if (timerHolder.id !== null) {
				clearTimeout(timerHolder.id)
			}
			try {
				socket?.close()
			} catch {
				/* ignore */
			}
			resolve(ok)
		}
		timerHolder.id = setTimeout(() => finish(false), timeoutMs)
		try {
			socket = new WebSocket(url)
		} catch {
			finish(false)
			return
		}
		socket.onopen = () => finish(true)
		socket.onerror = () => finish(false)
		socket.onclose = () => finish(false)
	})
}

export function usePolling(deps: PollDeps) {
	// One in-flight long-poll per bucket. Keyed by `${year}-${week}`.
	const weekPollAbortControllers = new Map<string, AbortController>()
	let shouldPollWeek = false
	let customPollAbortController: AbortController | null = null
	let shouldPollCustom = false
	let usingNotifyPush = false

	// --- Week polling ---

	function stopWeekPoll() {
		shouldPollWeek = false
		for (const c of weekPollAbortControllers.values()) {
			c.abort()
		}
		weekPollAbortControllers.clear()
	}

	async function pollBucket(year: number, week: number) {
		const key = bucketKey(year, week)
		if (!shouldPollWeek) {
			return
		}
		// If the visible window no longer includes this bucket, stop polling it.
		if (!deps.bucketKeys.value.some((b) => b.weekKey === key)) {
			weekPollAbortControllers.delete(key)
			return
		}
		const controller = new AbortController()
		weekPollAbortControllers.set(key, controller)
		try {
			const url = generateUrl('/apps/weekplanner/week/{year}/{week}/poll', {
				year: String(year),
				week: String(week),
			})
			const response = await axios.get<{ changed: boolean, updatedAt: number, data?: unknown }>(
				`${url}?since=${deps.getWeekKnownUpdatedAt(key)}`,
				{ signal: controller.signal, timeout: 35_000 },
			)
			if (response.data.changed && response.data.data !== undefined && response.data.data !== null) {
				if (deps.isWeekSaveIdle() && !deps.editingTask.value) {
					deps.setWeekKnownUpdatedAt(key, response.data.updatedAt)
					deps.applyBucketData(key, response.data.data as WeekData)
					deps.materializeRecurringTasks()
				}
			}
		} catch {
			if (controller.signal.aborted) {
				return
			}
			await new Promise((resolve) => setTimeout(resolve, 5_000))
		}
		pollBucket(year, week)
	}

	function longPollWeek() {
		if (!shouldPollWeek) {
			return
		}
		// Spin up one long-poll loop per bucket in the current visible window.
		for (const bucket of deps.bucketKeys.value) {
			if (!weekPollAbortControllers.has(bucket.weekKey)) {
				pollBucket(bucket.year, bucket.week)
			}
		}
	}

	// --- Custom columns polling ---

	function stopCustomPoll() {
		shouldPollCustom = false
		customPollAbortController?.abort()
		customPollAbortController = null
	}

	async function longPollCustom() {
		if (!shouldPollCustom) {
			return
		}
		const controller = new AbortController()
		customPollAbortController = controller
		try {
			const url = generateUrl('/apps/weekplanner/custom-columns/poll')
			const response = await axios.get<{ changed: boolean, updatedAt: number, data?: unknown }>(
				`${url}?since=${deps.getCustomKnownUpdatedAt()}`,
				{ signal: controller.signal, timeout: 35_000 },
			)
			if (response.data.changed) {
				if (deps.isCustomSaveIdle() && !deps.editingTask.value) {
					deps.setCustomKnownUpdatedAt(response.data.updatedAt)
					deps.applyCustomColumnsData(response.data.data)
				}
			}
		} catch {
			if (controller.signal.aborted) {
				return
			}
			await new Promise((resolve) => setTimeout(resolve, 5_000))
		}
		longPollCustom()
	}

	// --- Lifecycle helpers ---

	function startLongPolling() {
		shouldPollWeek = true
		longPollWeek()
		shouldPollCustom = true
		longPollCustom()
	}

	function stopAllPolling() {
		stopWeekPoll()
		stopCustomPoll()
	}

	// --- Notify push ---

	async function trySetupNotifyPush(): Promise<boolean> {
		try {
			let caps: { notify_push?: NotifyPushCapability }
			try {
				caps = getCapabilities() as { notify_push?: NotifyPushCapability }
			} catch {
				return false
			}
			const notifyPush = caps?.notify_push
			if (!notifyPush) {
				return false
			}

			// `mod.listen()` returns truthy whenever the notify_push capability
			// is advertised, not when the WebSocket actually connects. Without
			// this probe a broken proxy or unreachable backend silently kills
			// cross-device sync because the long-poll fallback never engages.
			const wsUrl = await resolveNotifyPushWebsocket(notifyPush)
			if (!wsUrl) {
				return false
			}
			notifyPush.endpoints = { ...(notifyPush.endpoints ?? {}), websocket: wsUrl }

			const mod = await import('@nextcloud/notify_push')

			const available = mod.listen('weekplanner_week_update', (_type, body) => {
				if (!body) {
					return
				}
				const key = bucketKey(Number(body.year), Number(body.week))
				if (deps.bucketKeys.value.some((b) => b.weekKey === key)) {
					if (deps.isWeekSaveIdle() && deps.isWeekLoadIdle() && !deps.editingTask.value) {
						deps.loadWeek()
					}
				}
			})

			if (!available) {
				return false
			}

			mod.listen('weekplanner_customcolumns_update', () => {
				if (deps.isCustomSaveIdle() && !deps.editingTask.value) {
					deps.loadCustomColumns()
				}
			})

			return true
		} catch {
			return false
		}
	}

	function isUsingNotifyPush() {
		return usingNotifyPush
	}

	function setUsingNotifyPush(val: boolean) {
		usingNotifyPush = val
	}

	return {
		stopWeekPoll,
		startLongPolling,
		stopAllPolling,
		trySetupNotifyPush,
		isUsingNotifyPush,
		setUsingNotifyPush,
		longPollWeek,
	}
}
